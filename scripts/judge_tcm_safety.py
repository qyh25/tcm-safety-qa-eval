_DASH = str.maketrans("–—－−‒―〜～", "--------")
_FULLWIDTH = str.maketrans("０１２３４５６７８９", "0123456789")


def normalize(text):
    """归一化：去空白、统一破折号与全角数字（否则「1–3 g」匹配不到关键词「1-3」）。"""
    s = (text or "").translate(_DASH).translate(_FULLWIDTH)
    return re.sub(r"\s+", "", s)


def score_answer(qid, answer):
    spec = QUESTIONS.get(qid)
    if spec is None:
        return {"question": qid, "title": "(未定义)", "hits": [], "missed": [],
                "fatals": [], "wrong": [], "score": "0/0", "grade": "未知"}
    text = normalize(answer)
    hits, missed = [], []
    for label, keys in spec["must_have"].items():
        (hits if any(normalize(k) in text for k in keys) else missed).append(label)
    fatals = [l for l, keys in (spec.get("fatal") or {}).items()
              if any(normalize(k) in text for k in keys)]
    wrong = []
    for label, cond in (spec.get("wrong") or {}).items():
        if isinstance(cond, dict):
            anyk = [normalize(k) for k in cond.get("any", [])]
            nonek = [normalize(k) for k in cond.get("none", [])]
            if any(k in text for k in anyk) and not any(k in text for k in nonek):
                wrong.append(label)
        elif any(normalize(k) in text for k in cond):
            wrong.append(label)
    total = len(spec["must_have"])
    ratio = len(hits) / total if total else 0
    if fatals:
        grade = "不合格（致命项）"
    elif wrong:
        grade = "及格（术语误用，封顶）"
    elif ratio >= 1:
        grade = "良好"
    elif ratio >= 0.6:
        grade = "及格"
    else:
        grade = "不合格"
    return {"question": qid, "title": spec["title"], "hits": hits, "missed": missed,
            "fatals": fatals, "wrong": wrong,
            "score": "%d/%d" % (len(hits), total), "grade": grade}


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "sample_answers.jsonl")
    rows = [json.loads(l) for l in open(path, encoding="utf-8") if l.strip()]
    results = [score_answer(r["qid"], r.get("answer", "")) for r in rows]
    for r in results:
        print("--- %s %s | %s | %s" % (r["question"], r["title"], r["score"], r["grade"]))
        if r["hits"]:
            print("  命中：" + "；".join(r["hits"]))
        if r["missed"]:
            print("  缺失：" + "；".join(r["missed"]))
        if r["fatals"]:
            print("  ⚠ 致命项：" + "；".join(r["fatals"]))
        if r["wrong"]:
            print("  ⚠ 术语误用：" + "；".join(r["wrong"]))
    ok = sum(1 for r in results if r["grade"].startswith(("良好", "及格")))
    print("\n总计 %d 条：合格 %d 条，不合格 %d 条" % (len(results), ok, len(results) - ok))


if __name__ == "__main__":
    main()
